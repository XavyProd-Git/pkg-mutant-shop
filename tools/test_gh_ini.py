def fail(msg):
    print("FAIL: %s" % msg)
    sys.exit(1)


# ---- lift the functions out of the payload -------------------------------------------------------

def extract(src, start_marker, end_func_name):
    """Return src from start_marker through the closing brace of end_func_name."""
    i = src.find(start_marker)
    if i < 0:
        fail("could not find %r in server_ps4.c - has it been renamed?" % start_marker)
    j = src.find(end_func_name, i)
    if j < 0:
        fail("could not find %r after %r" % (end_func_name, start_marker))
    # walk to the opening brace of that function, then match braces
    k = src.find("{", j)
    if k < 0:
        fail("no body for %s" % end_func_name)
    depth = 0
    while k < len(src):
        if src[k] == "{":
            depth += 1
        elif src[k] == "}":
            depth -= 1
            if depth == 0:
                return src[i:k + 1]
        k += 1
    fail("unbalanced braces after %s" % end_func_name)


