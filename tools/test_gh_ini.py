"""Test the REAL plugins.ini code out of the PS4 payload, on a PC, against a temporary file.

WHY THIS EXISTS. /data/GoldHEN/plugins.ini is the OWNER'S file. Every other GoldHEN plugin they run
is listed in it, it survives a reboot and a re-jailbreak, and a console left with a bad line in it
hangs on the next game launch with nothing of ours running to undo it. That is not a thing to edit
on trust, and an audit found six real defects in this code at once: a substring match that counted
prose as a listing, a scan that stopped at the first mention and so could not see a per-title arm, an
unreachable insertion branch that appended a second [default] section, two writers that silently lost
the tail of any line of 512 bytes or more, in-place O_TRUNC writes of the owner's file, and a purge
that rewrote it to byte-identical content on every single boot while announcing a removal.

HOW. The functions are LIFTED OUT OF server_ps4.c BY TEXT - not reimplemented here. A reimplementation
would test this file's idea of the code instead of the code, which is exactly the trap that let those
six through. server_ps4.c as a whole cannot compile on a PC (it is a PS4 payload), so a short prelude
supplies the handful of things the extracted region needs, GH_PLUGINS_INI is pointed at a temporary
file, and agent_deploy is stubbed because listing is what is under test, not writing the .prx.

Run it directly, or as one of the build gates. Exit code 0 means every check passed.
"""
