# -*- coding: utf-8 -*-
"""The PS4 cheat engine's two halves, compiled from the shipped sources and run against each other.

WHY THIS EXISTS. The agent protocol has already failed silently once, in a way no amount of
reading caught and no console could report. The shop put the length of its OUTGOING payload in the
request header; for a read that is zero; the agent refuses a zero length. So not a single memory
read could ever have succeeded - and from the mods panel that is indistinguishable from "no game is
running", which is what it looked like for weeks. The same build killed games outright, because a
write to a socket the shop had already closed raised SIGPIPE, and SIGPIPE's default action
terminates the process. The process was somebody's game.

Neither fault needed a PS4 to find. Both needed a test, and this is it.

WHAT IS ACTUALLY UNDER TEST. Not a model of the protocol - the protocol.
  * ps4-app/plugin/source/main.c is compiled as it ships, against ps4-app/plugin/test/stubinc,
    whose declarations are copied from the OpenOrbis toolchain's own headers.
  * the client half is LIFTED OUT of ps4-app/onconsole/server_ps4.c at run time, between the
    markers below, so editing either end changes what this compiles. There is no second copy to
    drift.
The stubs stand in for the console, not for either half of the protocol: a fake process whose
"modules" are three carved-out pieces of one mmap'd megabyte, with real gaps between them that are
readable memory and not part of any segment. That is what makes the refusal checks mean something.

    python tools/test_agent_protocol.py [--keep]

Needs WSL with gcc, the same place the console builds come from. With neither, it skips rather
than failing - a PC without the toolchain should not fail the suite - and says so.
"""
import io
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SERVER = os.path.join(ROOT, "ps4-app", "onconsole", "server_ps4.c")
PLUGIN = os.path.join(ROOT, "ps4-app", "plugin", "source", "main.c")
TESTDIR = os.path.join(ROOT, "ps4-app", "plugin", "test")

# The client block, by the lines that open and close it. Markers rather than line numbers so the
# file can grow without silently extracting the wrong thing.
START = "#define AGENT_OP_PING"
END = "/* The game the agent is sitting in, as pid + base"

PRELUDE = """/* GENERATED by tools/test_agent_protocol.py - do not edit, and do not commit.
 * The shop's agent client, lifted verbatim out of ps4-app/onconsole/server_ps4.c so the test
 * compiles the code that ships rather than a copy of it. */
#define _GNU_SOURCE
#include <arpa/inet.h>
#include <netinet/in.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include <sys/socket.h>
#include <sys/time.h>
#include <sys/types.h>
#include <unistd.h>
"""

WRAPPERS = """
/* The shipped functions are static, as they should be. These are the only additions. */
int t_agent_info(char *json, size_t jsz) { return agent_info(json, jsz); }
int t_mem_read(int pid, intptr_t a, void *b, size_t n)        { return mem_read((pid_t)pid, a, b, n); }
int t_mem_write(int pid, intptr_t a, const void *b, size_t n) { return mem_write((pid_t)pid, a, b, n); }
int t_agent_port(void) { return AGENT_PORT; }
"""


def fail(msg):
    print("  [FAIL] %s" % msg)
    return 1


def main():
    keep = "--keep" in sys.argv

    for p in (SERVER, PLUGIN):
        if not os.path.exists(p):
            print("test_agent_protocol: %s is missing - skipping" % p)
            return 0

    src = io.open(SERVER, encoding="utf-8", errors="replace").read()
    i = src.find(START)
    j = src.find(END, i + 1 if i >= 0 else 0)
    if i < 0 or j < 0:
        return fail("could not find the agent client between its markers in server_ps4.c "
                    "(start=%d end=%d) - if it moved, move the markers with it" % (i, j))
    client = src[i:j]
    for want in ("agent_req", "mem_read", "mem_write", "agent_info", "wirelen"):
        if want not in client:
            return fail("the extracted client has no %s in it - the markers are wrong" % want)

    # The one static assertion: the line whose absence killed games. Cheap, and it would survive a
    # rewrite of the test harness itself.
    plug = io.open(PLUGIN, encoding="utf-8", errors="replace").read()
    # ---- the static gate over main.c -------------------------------------------------------------
    #
    # IT READ CODE ONLY, AND IT CHECKED NOTHING. Both patterns below used to begin with a literal
    # ASCII backspace byte where a word-boundary \b was meant. main.c holds no such byte, so every
    # findall() returned an empty list and this suite reported "0 failures" for a gate that could not
    # fail. That is the same class of fault as the code it is here to guard, so it now carries its own
    # positive control at the end.
    import re as _re

    def _code_only(src):
        """main.c with comments AND string/char literals blanked, in ONE alternating pass.

        One pass, not two, and that is load-bearing: a stripper that removes comments first desyncs
        the moment a literal contains /*, and one that removes literals first desyncs on a quote
        inside a comment. This file is full of prose about signal() and stat() - main.c's own notes on
        why they are gone - so without this the gate reports them as calls for ever."""
        out = []
        k, n = 0, len(src)
        while k < n:
            c = src[k]
            if c == "/" and k + 1 < n and src[k + 1] == "*":
                e = src.find("*/", k + 2)
                k = n if e < 0 else e + 2
                out.append(" ")
            elif c == "/" and k + 1 < n and src[k + 1] == "/":
                e = src.find("\n", k)
                k = n if e < 0 else e
                out.append(" ")
            elif c == '"' or c == "'":
                q = c
                e = k + 1
                while e < n:
                    if src[e] == "\\":
                        e += 2
                        continue
                    if src[e] == q:
                        e += 1
                        break
                    if src[e] == "\n":          # unterminated - do not swallow the rest of the file
                        break
                    e += 1
                k = e
                out.append(" ")
            else:
                out.append(c)
                k += 1
        return "".join(out)

    # THE AGENT MUST IMPORT AS LITTLE AS POSSIBLE. An import the game's libraries cannot resolve fails
    # the module load, and that is exactly where this agent has been breaking games. So the raw POSIX
    # calls stay out and nothing here touches signals.
    # \b is what keeps this honest in both directions: it does NOT match inside fopen/fclose/fread/
    # fwrite, so the stdio the file channel is built on is untouched, and it does not match
    # write_atomic() either.
    BANNED = r"\b(signal|sigaction|mkdir|stat|lstat|fstat|unlink|open|close|read|write|"    \
             r"socket|bind|listen|accept)\s*\("
    # NO RAW printf ANYWHERE IN THE AGENT. libc printf can block on a stdout the game never drains,
    # and when that happens in plugin_load the game freezes on "Please wait..." for ever - the exact
    # failure the owner hit. snprintf into our own buffers is fine, and so is fwrite: the rule is about
    # writing to a STREAM that can block, and fwrite to a file we opened ourselves IS the channel.
    # fwrite used to be on this list, which meant reviving the gate would have condemned the design.
    PRINTFS = r"\b(printf|fprintf|vprintf|puts|fputs|perror)\s*\("
    # LIBC STDIO IS WHAT CRASHED GAMES, and this is the only rule here backed by a console result
    # rather than by caution. PMS_AGENT_NULL - plugin_load sets a global, returns, zero undefined
    # symbols - LOADED AND PLAYED Dark Souls II. PMS_AGENT_MINIMAL, identical but importing
    # fopen/fwrite/fclose and calling them, CRASHED it. The file-channel agent, calling the same stdio
    # from a worker thread six seconds in, also crashed it.
    # What misled us: game_patch imports fprintf, getc, putc and the stderr FILE object, which reads
    # like "the FILE machinery resolves inside a game" - but game_patch does its file work with
    # sceKernelOpen/Read/Write/Close/Lseek/Mkdir and never calls fopen. Those are different claims.
    # The agent uses the sceKernel* calls now, and none of these may come back.
    STDIO = (r"\b(fopen|freopen|fdopen|fread|fwrite|fclose|fflush|fgetc|fputc|getc|putc|fgets|"
             r"fseek|ftell|rewind|setbuf|setvbuf|tmpfile|rename|remove|unlink)\s*\(")

    plug = io.open(PLUGIN, encoding="utf-8", errors="replace").read()
    code = _code_only(plug)

    banned = sorted(set(m for m in _re.findall(BANNED, code) if m))
    if banned:
        return fail("main.c calls %s - the agent must use stdio only and touch no signals; an "
                    "import the game cannot resolve fails the module load"
                    % ", ".join(banned))

    bad = sorted(set(m for m in _re.findall(PRINTFS, code) if m))
    if bad:
        return fail("main.c still calls %s - raw stdio in the game can block and freeze it; "
                    "the agent must never log inside the game" % ", ".join(bad))

    stdio = sorted(set(m for m in _re.findall(STDIO, code) if m))
    if stdio:
        return fail("main.c calls %s - libc stdio is MEASURED to crash games from inside them "
                    "(a build importing only fopen/fwrite/fclose crashed Dark Souls II; the same "
                    "build with no imports loaded and played). Use sceKernelOpen/Read/Write/Close/"
                    "Lseek, which game_patch proves work inside a game." % ", ".join(stdio))

    # (d) THE POSITIVE CONTROL. Both patterns are run against a snippet that must trip them, and
    # against the shapes that must NOT. Without this, the two checks above can go back to matching
    # nothing and this file will keep reporting success - which is precisely what happened.
    CONTROL = (
        'void x(void){ signal(13, 0); socket(2,1,0); printf("a"); fputs("b", f); }\n'
        '/* prose about stat() and signal() and fopen() that must not count */\n'
        'void y(void){ char b[8]; snprintf(b, 8, "%d", 1); fopen("p","rb"); fwrite(b,1,1,f);\n'
        '  fclose(f); fread(b,1,1,f); write_atomic("a","b",0,0); }\n'
        'void z(void){ sceKernelOpen("p",0,0); sceKernelRead(1,b,2); sceKernelWrite(1,b,2);\n'
        '  sceKernelClose(1); sceKernelLseek(1,0,2); }\n'
        'const char *s = "signal( socket( printf( fopen( inside a literal";\n')
    cc = _code_only(CONTROL)
    cb = sorted(set(_re.findall(BANNED, cc)))
    cp = sorted(set(_re.findall(PRINTFS, cc)))
    cs = sorted(set(_re.findall(STDIO, cc)))
    if cb != ["signal", "socket"]:
        return fail("the banned-call gate is broken: control expected ['signal', 'socket'], got %r" % cb)
    if cp != ["fputs", "printf"]:
        return fail("the raw-stdio gate is broken: control expected ['fputs', 'printf'], got %r" % cp)
    # It must catch the stdio family AND leave the sceKernel* replacements alone - a pattern that
    # flagged sceKernelOpen would make the actual fix unshippable.
    if cs != ["fclose", "fopen", "fread", "fwrite"]:
        return fail("the stdio gate is broken: control expected fopen/fread/fwrite/fclose, got %r" % cs)

    gen = os.path.join(TESTDIR, "client_generated.c")
    io.open(gen, "w", encoding="utf-8", newline="\n").write(PRELUDE + client + WRAPPERS)

    def wsl(path):
        p = os.path.abspath(path).replace("\\", "/")
        if len(p) > 1 and p[1] == ":":
            p = "/mnt/" + p[0].lower() + p[2:]
        return p

    binp = wsl(os.path.join(TESTDIR, "agent_protocol_test"))
    # Every path is quoted: this project lives under a directory with a space in its name, and an
    # unquoted path makes the compile fail in a way that reads like a broken test.
    # -DPMS_AGENT_START_DELAY_US=0: the production agent waits a few seconds before opening its
    # socket, so it never races a game's load screen. On a PC there is no game and nothing to wait
    # for, so the test builds that delay out - otherwise every run would sleep for no reason.
    # The agent is pointed at a temporary directory (there is no /data on a PC), started with no
    # delay (nothing to wait for here) and polled fast so the suite is quick.
    tdir = wsl(os.path.join(TESTDIR, "chan"))
    cmd = ("set -e; cd '%s'; rm -rf '%s'; mkdir -p '%s'; "
           "gcc -O1 -g -Wall -Wno-unused-function -pthread "
           "-DPMS_AGENT_START_DELAY_US=0 -DPMS_AGENT_POLL_US=20000 "
           "-DPMS_AGENT_DIR_OVERRIDE='\"%s\"' "
           "-o '%s' harness.c '%s' -I. -Istubinc 2>&1"
           % (wsl(TESTDIR), tdir, tdir, tdir, binp, wsl(PLUGIN)))

    try:
        b = subprocess.run(["wsl", "bash", "-lc", cmd], capture_output=True, text=True, timeout=300)
    except FileNotFoundError:
        print("test_agent_protocol: WSL is not available on this PC - skipping")
        return 0
    except subprocess.TimeoutExpired:
        return fail("the compile timed out")

    out = (b.stdout or "") + (b.stderr or "")
    if b.returncode != 0:
        if "gcc: not found" in out or "command not found" in out:
            print("test_agent_protocol: WSL has no gcc - skipping")
            return 0
        print(out.strip()[:4000])
        return fail("the test did not compile")
    if out.strip():
        print("  compiler said:\n" + out.strip()[:2000])

    try:
        r = subprocess.run(["wsl", "bash", "-lc", "'%s'" % binp],
                           capture_output=True, text=True, timeout=300)
    except subprocess.TimeoutExpired:
        return fail("the test hung - an agent that never answers is exactly the failure mode "
                    "this exists to catch")
    print((r.stdout or "").rstrip())
    if r.stderr and r.stderr.strip():
        print("  stderr: " + r.stderr.strip()[:1000])

    if not keep:
        for p in (gen, os.path.join(TESTDIR, "agent_protocol_test")):
            try:
                os.remove(p)
            except OSError:
                pass

    if r.returncode < 0 or r.returncode > 1:
        # A process killed by a signal is the original bug walking back in: SIGPIPE from inside the
        # agent, which on a console takes the game with it.
        return fail("the test process died (exit %d) instead of reporting - if that is signal 13, "
                    "SIGPIPE is fatal again" % r.returncode)
    return r.returncode


if __name__ == "__main__":
    sys.exit(main())
